// Generates sw-precache.js: the list of app-shell files (code, styles, small data, icons) the service worker caches on install, plus a version hash.
// Big, rarely-changing assets (sprite atlases, .glb models) are NOT precached: the service worker caches them the first time they are used.
//   node tools/build_sw_manifest.mjs        (run before packaging; the file is committed)
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
const ROOT = new URL('..', import.meta.url).pathname;
const SKIP_DIR = new Set(['.git', 'node_modules', 'tests', 'tools', 'docs', 'exports', '__pycache__', 'android', 'unreal']);
const SKIP_PREFIX = ['assets/sprites/', 'assets/models/', 'assets/models3d/'];
const EXT = /\.(html|js|mjs|css|json|csv|webmanifest|png|svg|webp|jpg|woff2?)$/i;
const out = [];
(function walk(dir) {
  for (const n of readdirSync(dir)) {
    const p = join(dir, n), st = statSync(p), rel = relative(ROOT, p).split(sep).join('/');
    if (st.isDirectory()) { if (!SKIP_DIR.has(n)) walk(p); continue; }
    if (!EXT.test(n) || n === 'sw.js' || n === 'sw-precache.js' || n.endsWith('.zip') || SKIP_PREFIX.some(s => rel.startsWith(s))) continue;
    if (/(^|\/)package(-lock)?\.json$/.test(rel)) continue;
    out.push({ rel, size: st.size });
  }
})(ROOT);
out.sort((a, b) => (a.rel < b.rel ? -1 : 1));
let h = 0x811c9dc5; for (const f of out) { const s = `${f.rel}:${f.size};`; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; } }
const version = h.toString(16).padStart(8, '0');
writeFileSync(join(ROOT, 'sw-precache.js'), `// GENERATED by tools/build_sw_manifest.mjs — do not edit.\nself.ASU_SW = ${JSON.stringify({ version, urls: ['./', ...out.map(f => f.rel)] })};\n`);
console.log(`sw-precache.js: ${out.length} files, ${Math.round(out.reduce((s, f) => s + f.size, 0) / 1024)} KB, version ${version}`);
